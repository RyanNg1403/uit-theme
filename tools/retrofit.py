def dawn() -> int:
    rng = random.Random(5)
    svg = base("dawn")
    for c in ("ride", "moto"):
        svg = drop(svg, c)
    lay = Layer()
    m = Lite(lay)
    cast = Cast(m, "rd")
    # A jogger and an early walker on the path by the grass.
    jog = Look(skin=SKIN[1], hair=HAIR[0], shirt="#ff7a5a", pants="#2a3050", shoes="#f4f4fa")
    cast.walker(jog, 15, 186, False, 0.3, period=0.62, stride=0.95, gap=80, arms=None)
    cast.walker(Look(skin=SKIN[3], hair="#c8c8d0", shirt="#eef2fa", pants="#5a6a8a", sleeves="long"), 14, 186, True, 0.7, period=1.3, gap=120)
    # Scooters heading into the city, cyclists heading for campus.
    helmets = ["#f4f4fa", "#2a5ab0", "#c83a3a", "#ffd34a"]
    for i, (col, passenger) in enumerate([("#3a6ac8", False), ("#e8e8f4", True), ("#c83a3a", False)]):
        bk, fr = scooter(col)
        b_id, f_id = cast.raw(f"sb{col}", bk), cast.raw(f"sf{col}", fr)
        people = []
        if passenger:
            pas = Look(skin=SKIN[0], helmet="#ff8fb3", hair_style="long", shirt="#ffffff", pants="#2a3050", bag="#b04a3a")
            people.append(f'<g transform="translate(-8 {seat_feet(15, -13):.1f})"><use href="#{cast.sid(pas, 15, ride(arms=25, elbows=50))}"/></g>')
        rid = Look(skin=rng.choice(SKIN), helmet=helmets[i], shirt=rng.choice(["#eef2fa", "#3a5ab0", "#7a9a5a"]), sleeves="long", pants="#22263e")
        people.append(f'<g transform="translate(-3 {seat_feet(15, -13):.1f})"><use href="#{cast.sid(rid, 15, ride())}"/></g>')
        cast.vehicle(b_id, people, f_id, 196, False, rng.uniform(15, 19), i / 3 + rng.uniform(0, 0.1))
    for i, (frame, shirt) in enumerate([("#e84a4a", "#ffffff"), ("#2f6fe0", "#3a8ad8"), ("#e84a4a", "#ffd34a"), ("#3a8a6a", "#eef2fa")]):
        look = Look(skin=rng.choice(SKIN), hair=rng.choice(HAIR), hair_style=rng.choice(["short", "pony", "bob"]), shirt=shirt, pants="#22263e", bag=rng.choice(["#2f5fb0", "#222838", None]))
        pedals = cast.steps([cast.sid(look, 16, pedal(k)) for k in range(4)], 0.7, rng.uniform(0, 1))
        cast.vehicle(cast.raw(f"cy{frame}", bicycle(frame)), [f'<g transform="translate(-4 {seat_feet(16, -13):.1f})">{pedals}</g>'], None, 209, True, rng.uniform(26, 34), i / 4 + rng.uniform(0, 0.1))
    return write("dawn", "campus dawn, people retrofitted", splice(svg, lay))


def trungthu() -> int:
    rng = random.Random(8)
    svg = drop(base("trungthu"), "parade")
    lay = Layer()
    m = Lite(lay)
    cast = Cast(m, "rt")
    glow = m.glow_def("#ffb040", 0.45)
    hold = (118, -10), (-62, 14)
    for i in range(6):
        col = ["#e2303a", "#ffb040", "#ff6ab0", "#4aa0ff", "#e2303a", "#ffd34a"][i]
        look = Look(skin=rng.choice(SKIN), hair=rng.choice(HAIR), hair_style=rng.choice(["short", "bob", "pony"]), shirt=rng.choice(["#3a5a9a", "#c84a4a", "#4a8a5a", "#e8b04a", "#7a5ab0"]), pants="#2a2a3a", prop="lantern", extra={"lantern": col})
        hh = rng.choice([12, 13, 14])
        lead = f'<circle cx="4" cy="{-hh - 1}" r="7" fill="url(#{glow})"/>'
        cast.walker(look, hh, 203 + rng.randint(-1, 1), True, i / 6 + rng.uniform(0, 0.05), period=0.9, gap=40, n=6, arms=hold[0], elbows=hold[1], lead=lead)
    return write("trungthu", "Trung Thu night, people retrofitted", splice(svg, lay))


