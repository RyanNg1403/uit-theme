"""Give the older hand-made scenes rig people.

usage: uv run python tools/retrofit.py [scene ...]

The older scenes' generators are gone; their SVGs are kept in tools/base/. This drops
their tiny sprite people and adds rig characters (tools/rig.py, tools/people.py) in
their place, writing hooks/scenes/<name>.ts and drafts/out/<name>.svg.
"""

from __future__ import annotations

import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(__file__))

