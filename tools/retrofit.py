def tet() -> int:
    rng = random.Random(10)
    svg = base("tet")
    lay = Layer()
    m = Lite(lay)
    cast = Cast(m, "re")
    # Two friends in ao dai strolling, a scooter bringing home a potted mai tree.
    for i, (dress, hair, right, ph) in enumerate([("#d8283a", "#14121e", True, 0.1), ("#f2b630", "#2a1e1a", True, 0.118)]):
        look = Look(skin=SKIN[3 - i], hair=hair, hair_style="long", dress=dress, pants="#f4ece2", shoes="#2a1a1a")
        cast.walker(look, 24, 206 + i, right, ph, period=1.25, gap=100)
    kid = Look(skin=SKIN[0], hair="#1a1626", shirt="#e2303a", pants="#2a2a3a", hold=None, prop="folder", extra={"folder": "#e2303a"})
    cast.walker(kid, 15, 208, True, 0.13, period=0.8, gap=100, arms=(10, -16), elbows=(30, 20))
    bk, fr = scooter("#3a5ab0")
    tree = Canvas()
    tree.rect(-16, -12, 6, 4, "#a83a2a")
    tree.hline(-16, -12, 6, "#c85a3a")
    for k in range(40):
        tx, ty = rng.uniform(-24, -2), rng.uniform(-34, -14)
        if (tx + 13) ** 2 / 120 + (ty + 24) ** 2 / 90 < 1:
            tree.set(tx, ty, rng.choice(["#ffd34a", "#ffe680", "#f2b630"]))
    for a, b_ in [((-13, -12), (-16, -26)), ((-13, -12), (-8, -24)), ((-15, -20), (-20, -28))]:
        tree.line(*a, *b_, "#5a3a24")
    rid = Look(skin=SKIN[2], helmet="#c83a3a", shirt="#eef2fa", sleeves="long", pants="#22263e")
    people = [f'<use href="#{cast.raw("mai", tree)}"/>', f'<g transform="translate(-3 {seat_feet(15, -13):.1f})"><use href="#{cast.sid(rid, 15, ride())}"/></g>']
    head = m.glow_def("#fff2b8", 0.6)
    cast.vehicle(cast.raw("sbt", bk), people, cast.raw("sft", fr), 196, False, 22, 0.5, gap=200, glow=f'<circle cx="11" cy="-14" r="5" fill="url(#{head})"/>')
    return write("tet", "Tet night, people retrofitted", splice(svg, lay))


def exam() -> int:
    rng = random.Random(11)
    svg = base("exam")
    lay = Layer()
    m = Lite(lay)
    cast = Cast(m, "rx")
    # Two students at the long desk: one writing, one reading and turning pages.
    hh, feet = 62, 182
    w1 = Look(skin=SKIN[3], hair="#1a1626", hair_style="long", shirt="#d8d0e8", sleeves="long", pants="#2a2030")
    write_ = [Pose(arms=(34, 26), elbows=(56 + d, 50), lean=4, blink=i == 7) for i, d in enumerate([0, 8, 0, 8, 0, 8, 0, 0])]
    cast.stay(w1, hh, 112, feet, write_, 2.4, 0, crop=151)
    r1 = Look(skin=SKIN[1], hair="#2a1e1a", hair_style="short", shirt="#5a7ab0", sleeves="long", pants="#2a2030", prop="folder", extra={"folder": "#c84a4a"})
    read = [Pose(arms=(26, 22), elbows=(96, 90), lean=1, blink=i == 5) for i in range(8)]
    read[6] = Pose(arms=(30, 22), elbows=(104, 90), lean=1)
    cast.stay(r1, hh, 188, feet, read, 9, 3, facing=-1, crop=151)
    return write("exam", "exam night in the library, people retrofitted", splice(svg, lay, before='<rect y="150" width="384" height="3"'))


