from rig import Look, Pose, walk  # noqa: E402
from scenekit import check_size, new_palette, prune, tidy  # noqa: E402

VG = '<rect width="384" height="216" fill="url(#vg)"/>'
SKIN = ["#e0a982", "#d39a74", "#c88a66", "#ecb894"]
HAIR = ["#1a1626", "#2a1e1a", "#14121e", "#3a2618"]


class Layer:
    """Collects the CSS, defs and body that get spliced into a base scene."""

    def __init__(self):
        self.css: list[str] = []
        self.defs: list[str] = []
        self.body: list[str] = []

    def style(self, *r: str) -> None:
        self.css.extend(r)

    def add(self, *svg: str) -> None:
        self.body.extend(svg)


class Lite(Motion):
    """Motion helpers without the shared CSS, which would clash with the base scene's."""

    def __init__(self, layer: Layer):
        self.s = layer
        self.n = 0


def drop(svg: str, cls: str) -> str:
    """Remove every <g class="cls ..."> element, children and all."""
    while (j := svg.find(f'<g class="{cls}"')) >= 0 or (j := svg.find(f'<g class="{cls} ')) >= 0:
        k, depth = j, 0
        while True:
            o, c = svg.find("<g", k + 1), svg.find("</g>", k + 1)
            if o != -1 and o < c:
                depth += 1
                k = o
            elif depth == 0:
                k = c + 4
                break
            else:
                depth -= 1
                k = c
        svg = svg[:j] + svg[k:]
    return svg


def splice(svg: str, layer: Layer, before: str = "</g>" + VG) -> str:
    """CSS into <style>, defs into <defs>, the body before `before` (by default the end
    of the pixel group, so it draws on top of the scene and under the vignette)."""
    svg = svg.replace("</style>", tidy("".join(layer.css)) + "</style>", 1)
    svg = svg.replace("</defs>", tidy("".join(prune(layer.defs, *layer.body))) + "</defs>", 1)
    i = svg.index(before)
    return svg[:i] + tidy("".join(layer.body)) + svg[i:]


def write(name: str, header: str, svg: str) -> int:
    check_size(name, svg)
    os.makedirs("drafts/out", exist_ok=True)
    with open(f"drafts/out/{name}.svg", "w") as f:
        f.write(svg)
    with open(f"hooks/scenes/{name}.ts", "w") as f:
        f.write(f"// Generated by tools/retrofit.py from tools/base/{name}.svg: {header}, all vector.\nexport const SCENE = {json.dumps(svg)}\n")
    return len(svg)


def base(name: str) -> str:
    new_palette()
    with open(f"tools/base/{name}.svg") as f:
        return f.read()


